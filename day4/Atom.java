public class Atom {
    public static void Hydrogen() {
        System.out.println("Hydrogen is the lightest element.");
    }
    
    public static void Helium() {
        System.out.println("Helium is used in balloons.");
    }
    
    public static void Lithium() {
        System.out.println("Lithium is used in batteries.");
    }
    
    public static void Carbon() {
        System.out.println("Carbon is the basis of life.");
    }
    
    public static void Oxygen() {
        System.out.println("Oxygen is essential for respiration.");
    }
    
    public static void Neon() {
        System.out.println("Neon is used in bright signs.");
    }
    
    public static void Sodium() {
        System.out.println("Sodium is found in table salt.");
    }
    
    public static void Magnesium() {
        System.out.println("Magnesium is important for the human body.");
    }
    
    public static void Aluminum() {
        System.out.println("Aluminum is lightweight and strong.");
    }
    
    public static void Silicon() {
        System.out.println("Silicon is used in electronics.");
    }
    
    public static void main(String[] args) {
        Hydrogen();
        Helium();
        Lithium();
        Carbon();
        Oxygen();
        Neon();
        Sodium();
        Magnesium();
        Aluminum();
        Silicon();
    }
}
